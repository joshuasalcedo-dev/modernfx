    static String safe(String className) {
        return className.replace(':', '_').replace('.', '_').replace('/', '_');
    }

    static String block(String css, String selector) {
        int at = css.indexOf(selector + " {");
        if (at < 0) {
            throw new IllegalArgumentException("no '" + selector + " {' block");
        }
        int open = css.indexOf('{', at);
        int depth = 0;
        for (int i = open; i < css.length(); i++) {
            if (css.charAt(i) == '{') {
                depth++;
            } else if (css.charAt(i) == '}' && --depth == 0) {
                return css.substring(open + 1, i);
            }
        }
        throw new IllegalArgumentException("'" + selector + "' block is not closed");
    }

    static Map<String, String> vars(String css) {
        Map<String, String> m = new LinkedHashMap<>();
        Matcher v = Pattern.compile("--([a-zA-Z0-9-]+)\\s*:\\s*([^;]+);").matcher(css.replaceAll("/\\*.*?\\*/", ""));
        while (v.find()) {
            m.put(v.group(1), v.group(2).replaceAll("\\s+", " ").trim());
        }
        return m;
    }

    static double px(String v) {
        v = v.trim();
        if (v.endsWith("rem")) {
            return Double.parseDouble(v.substring(0, v.length() - 3)) * REM;
        }
        if (v.endsWith("px")) {
            return Double.parseDouble(v.substring(0, v.length() - 2));
        }
        return Double.parseDouble(v);
    }

    static String fmt(double d) {
        if (d == Math.rint(d)) {
            return String.valueOf((long) d);
        }
        String s = String.format(Locale.ROOT, "%.3f", d);
        return s.replaceAll("0+$", "").replaceAll("\\.$", "");
    }

    /** sRGB color with alpha, read from oklch(), #hex or rgb(). */
    record Color(double r, double g, double b, double a) {

        static boolean isColor(String v) {
            v = v.trim();
            return v.startsWith("oklch(") || v.startsWith("#") || v.startsWith("rgb");
        }

        static Color parse(String v) {
            v = v.trim();
            if (v.startsWith("#")) {
                String h = v.substring(1);
                if (h.length() == 3) {
                    h = "" + h.charAt(0) + h.charAt(0) + h.charAt(1) + h.charAt(1) + h.charAt(2) + h.charAt(2);
                }
                return new Color(Integer.parseInt(h.substring(0, 2), 16) / 255.0,
                        Integer.parseInt(h.substring(2, 4), 16) / 255.0, Integer.parseInt(h.substring(4, 6), 16) / 255.0, 1);
            }
            String inner = v.substring(v.indexOf('(') + 1, v.lastIndexOf(')')).trim();
            String[] alphaSplit = inner.split("/");
            String[] parts = alphaSplit[0].trim().split("[\\s,]+");
            double alpha = alphaSplit.length > 1 ? number(alphaSplit[1], 1) : 1;
            if (v.startsWith("rgb")) {
                return new Color(number(parts[0], 255) / 255, number(parts[1], 255) / 255, number(parts[2], 255) / 255, alpha);
            }
            double l = number(parts[0], 1);
            double c = parts[1].equals("none") ? 0 : number(parts[1], 0.4);
            double h = parts[2].equals("none") ? 0 : Double.parseDouble(parts[2]);
            return oklch(l, c, h, alpha);
        }

        /** "50%" is 0.5 (of scale for percentages), plain numbers stay. */
        static double number(String s, double percentScale) {
            s = s.trim();
            if (s.endsWith("%")) {
                return Double.parseDouble(s.substring(0, s.length() - 1)) / 100 * percentScale;
            }
            return Double.parseDouble(s);
        }

        static Color oklch(double l, double c, double hDeg, double alpha) {
            double h = Math.toRadians(hDeg);
            double a = c * Math.cos(h);
            double b = c * Math.sin(h);
            double l_ = l + 0.3963377774 * a + 0.2158037573 * b;
            double m_ = l - 0.1055613458 * a - 0.0638541728 * b;
            double s_ = l - 0.0894841775 * a - 1.2914855480 * b;
            double L = l_ * l_ * l_, M = m_ * m_ * m_, S = s_ * s_ * s_;
            double r = 4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S;
            double g = -1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S;
            double bl = -0.0041960863 * L - 0.7034186147 * M + 1.7076147010 * S;
            return new Color(gamma(r), gamma(g), gamma(bl), alpha);
        }

        static double gamma(double x) {
            double v = x <= 0.0031308 ? 12.92 * x : 1.055 * Math.pow(x, 1 / 2.4) - 0.055;
            return Math.min(1, Math.max(0, v));
        }

        Color withAlpha(double alpha) {
            return new Color(r, g, b, alpha);
        }

        String css() {
            int R = (int) Math.round(r * 255), G = (int) Math.round(g * 255), B = (int) Math.round(b * 255);
            if (a >= 0.9995) {
                return String.format("#%02x%02x%02x", R, G, B);
            }
            return "rgba(%d, %d, %d, %s)".formatted(R, G, B, fmt(Math.round(a * 1000) / 1000.0));
        }
    }
